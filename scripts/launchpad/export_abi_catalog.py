#!/usr/bin/env python3
"""Derive the published ABI catalog (apps/abi/) from the frozen deployment bundle.

Input authority: deployments/monad-testnet/abi/ (generated by export_deployed_abis.py
from pinned qualified sources). Every input ABI is hash-revalidated before copying, so
the catalog can never drift from the frozen bundle it was derived from.

Emits apps/abi/<Contract>.json (byte-identical), apps/abi/abi.ts (generated barrel),
and apps/abi/manifest.json (catalog schema v2 with ownership, coverage and explorer
verification status). Does not compile, does not touch frozen outputs.
"""
