def sha256_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export():
    bundle_manifest = json.loads((BUNDLE / 'manifest.json').read_text())
    by_name = {}
    for contract in bundle_manifest['contracts']:
        entry = dict(contract)
        existing = by_name.get(entry['contractName'])
        if existing is None:
            role = entry.pop('role')
            entry['deployments'] = [{'role': role, 'address': entry['address']}]
            by_name[entry['contractName']] = entry
        else:
            role = entry.pop('role')
            existing['deployments'].append({'role': role, 'address': entry['address']})

    CATALOG.mkdir(parents=True, exist_ok=True)
    for stale in CATALOG.glob('*.json'):
        if stale.name not in ('manifest.json',):
            stale.unlink()

    catalog_contracts = []
    files = {}
    for name, entry in sorted(by_name.items()):
        source_file = BUNDLE / entry['abi']
        abi = json.loads(source_file.read_text())
        assert isinstance(abi, list) and abi, name
        # Revalidate the frozen bundle hash before deriving from it.
        assert entry['abiSHA256'] == sha256_file(source_file), f'Bundle hash drift: {name}'
        target_file = CATALOG / (name + '.json')
        shutil.copyfile(source_file, target_file)
        assert sha256_file(target_file) == entry['abiSHA256']
        files[name] = entry['abiSHA256']
        catalog_contracts.append({
            'contractName': name,
            'abiFile': name + '.json',
            'abiSHA256': entry['abiSHA256'],
            'roles': sorted({d['role'] for d in entry['deployments']}),
            'address': entry['deployments'][0]['address'],
            'deployments': entry['deployments'],
            'dynamicInstances': bool(bundle_manifest.get('templates', {}).get(
                next((d['role'].removeprefix('demo.') for d in entry['deployments'] if d['role'].startswith('demo.')), ''))) or None,
            'coverage': entry['coverage'],
            'ownership': OWNERSHIP[name],
            'origin': entry.get('origin'),
            'compiler': entry.get('compiler'),
            'functions': entry.get('functions'),
            'events': entry.get('events'),
            'errors': entry.get('errors'),
            'verification': VERIFICATION.get(name) or {
                'status': 'NOT_SUBMITTED',
                'reason': 'Third-party owned source; not published as RetroPick-owned.',
            },
        })
        catalog_contracts[-1] = {k: v for k, v in catalog_contracts[-1].items() if v is not None}

    manifest = {
        'schemaVersion': 2,
        'catalog': 'retropick-v2-monad-testnet',
        'description': 'Published JSON ABI catalog derived from the frozen deployment bundle.',
        'chainId': bundle_manifest['chainId'],
        'deploymentBlock': bundle_manifest['deploymentBlock'],
        'deployedSourceSHA': bundle_manifest['deployedSourceSHA'],
        'kuruSDKSourceSHA': bundle_manifest.get('kuruSDKSourceSHA'),
        'kuruContractsSourceSHA': bundle_manifest.get('kuruContractsSourceSHA'),
        'derivedFrom': {
            'bundle': 'deployments/monad-testnet/abi/',
            'bundleManifestSHA256': sha256_file(BUNDLE / 'manifest.json'),
            'limitations': bundle_manifest.get('limitations'),
        },
        'verification': {
            'recordedAt': VERIFICATION_RECORDED_AT,
            'evidence': 'evidence/launchpad/v2-monad-testnet/source-verification-foundry.md',
            'sourcifyEndpoints': VERIFICATION[list(VERIFICATION)[0]]['endpoints'] if VERIFICATION else [],
            'note': 'exact_match = runtime bytecode identity confirmed by Sourcify recompilation.',
        },
        'templates': bundle_manifest.get('templates', {}),
        'contracts': catalog_contracts,
        'generatedAt': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
    }
    (CATALOG / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')

    # Generated TS barrel so bundler-resolution consumers need no resolveJsonModule.
    lines = [
        '// GENERATED by scripts/launchpad/export_abi_catalog.py — do not edit.',
        f'// Derived from deployments/monad-testnet/abi/ (deployed source {bundle_manifest["deployedSourceSHA"]}).',
        '// Each export is the complete artifact ABI from the JSON file of the same contract.',
    ]
    for name, symbol in EXPORT_NAMES.items():
        if name not in files:
            continue
        abi = json.loads((CATALOG / (name + '.json')).read_text())
        lines.append('export const ' + symbol + ' = ' + json.dumps(abi, separators=(',', ':')) + ' as const;')
    (CATALOG / 'abi.ts').write_text('\n\n'.join(lines) + '\n')

    summary = {'abiFiles': len(files), 'owned': sum(1 for c in catalog_contracts if c['ownership'] == 'RETROPICK_OWNED'),
               'upstream': sum(1 for c in catalog_contracts if c['ownership'].startswith('UPSTREAM')),
               'external': sum(1 for c in catalog_contracts if c['ownership'].startswith('EXTERNAL'))}
    print(json.dumps(summary))
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    export()
